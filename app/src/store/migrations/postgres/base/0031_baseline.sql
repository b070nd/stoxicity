-- Baseline of the base schema in Postgres, equal to the SQLite migrations 0001 to
-- 0031 together. From here on a migration is written for both databases with
-- the same number (see migrations/sqlite). Column types: INTEGER is BIGINT (the
-- times are unix milliseconds), REAL is DOUBLE PRECISION, JSON stays TEXT so the
-- stored bytes are what was written. Text sorts by bytes (the database is
-- created that way, and OpenPostgres checks it).

CREATE FUNCTION append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% is append-only', TG_TABLE_NAME USING ERRCODE = 'integrity_constraint_violation';
END;
$$;


