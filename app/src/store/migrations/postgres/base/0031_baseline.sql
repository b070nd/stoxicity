-- The full-text index: one column the match expressions of the filter package are
-- answered from. Words are runs of letters and digits, as the SQLite index splits
-- them, so "BRK.B" is the words brk and b.
ALTER TABLE articles ADD COLUMN fts tsvector GENERATED ALWAYS AS (
    to_tsvector('simple', regexp_replace(title || ' ' || summary || ' ' || tickers, '[^[:alnum:]]+', ' ', 'g'))) STORED;
CREATE INDEX articles_fts_idx ON articles USING gin (fts);

