CREATE FUNCTION pf_tx_check() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.seq <> COALESCE((SELECT MAX(seq) FROM pf_tx WHERE book_id = NEW.book_id), 0) + 1 THEN
        RAISE EXCEPTION 'pf_tx: the sequence of a book has no gaps' USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF (SELECT status FROM pf_books WHERE id = NEW.book_id) <> 'active' THEN
        RAISE EXCEPTION 'pf_tx: the book is archived' USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF NEW.recorded_ms < COALESCE((SELECT MAX(recorded_ms) FROM pf_tx WHERE book_id = NEW.book_id), 0) THEN
        RAISE EXCEPTION 'pf_tx: recorded time cannot go backwards' USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER pf_tx_check BEFORE INSERT ON pf_tx FOR EACH ROW EXECUTE FUNCTION pf_tx_check();

CREATE FUNCTION pf_books_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'a book is never deleted' USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF NOT (OLD.status = 'active' AND NEW.status = 'archived' AND OLD.env <> 'real'
            AND NEW.archived_ms IS NOT NULL
            AND NEW.id = OLD.id AND NEW.tenant_id = OLD.tenant_id AND NEW.account = OLD.account
            AND NEW.name = OLD.name AND NEW.env = OLD.env AND NEW.base = OLD.base
            AND NEW.method = OLD.method AND NEW.allow_negative_cash = OLD.allow_negative_cash
            AND NEW.created_ms = OLD.created_ms) THEN
        RAISE EXCEPTION 'pf_books: only a paper book can be archived, and nothing else changes' USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER pf_books_no_delete BEFORE DELETE ON pf_books FOR EACH ROW EXECUTE FUNCTION pf_books_guard();
CREATE TRIGGER pf_books_archive_only BEFORE UPDATE ON pf_books FOR EACH ROW EXECUTE FUNCTION pf_books_guard();
CREATE TRIGGER pf_books_no_truncate BEFORE TRUNCATE ON pf_books FOR EACH STATEMENT EXECUTE FUNCTION append_only();
